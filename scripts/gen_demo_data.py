"""Generate the frontend fallback data from the real scoring pipeline."""
import json
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
ROOT = SCRIPT_DIR.parent
sys.path.insert(0, str(SCRIPT_DIR))

from demo_projects import build_all  # noqa: E402


def main() -> None:
    records = build_all()
    project_list = [
        {
            "project_id": record["project"]["id"],
            "verra_id": record["project"]["verra_id"],
            "name": record["project"]["name"],
            "country": record["project"]["country"],
            "registry": record["project"]["registry"],
            "status": record["project"]["status"],
            "composite_score": record["score"]["composite_score"],
            "risk_flag": record["score"]["risk_flag"],
            "geometry_wkt": record["claim"]["geometry_wkt"],
        }
        for record in records
    ]
    details = {str(record["project"]["id"]): record for record in records}
    output = """// GENERATED by scripts/gen_demo_data.py: do not edit by hand.
// Illustrative demo projects (fictional names). Numbers are synthetic but are
// computed with the real scoring functions. Used when the API is unreachable.
import type { ProjectDetail, ScoreListItem } from "@/types";

export const DEMO_PROJECTS: ScoreListItem[] = %s;

export const DEMO_DETAILS: Record<string, ProjectDetail> = %s;

export function demoDetail(projectId: string): ProjectDetail | null {
  return DEMO_DETAILS[projectId] ?? null;
}
""" % (
        json.dumps(project_list, indent=2, ensure_ascii=False),
        json.dumps(details, indent=2, ensure_ascii=False),
    )
    (ROOT / "src/lib/demoData.ts").write_text(output, encoding="utf-8")
    for record in records:
        score = record["score"]
        verification = record["verification"]
        print(
            f"{record['project']['verra_id']} | {score['composite_score']} | "
            f"{score['risk_flag']} | {verification['credit_flag']} | "
            f"{','.join(score['flag_reasons']) or '-'}"
        )


if __name__ == "__main__":
    main()
